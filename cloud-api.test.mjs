import assert from 'node:assert/strict';
import { UniLoopCloud, CloudError } from './dist/cloud-api.js';

const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
const calls = [];
const fetcher = async (url, opts) => {
  calls.push({ url, ...opts });
  const result = url.includes('grant_type=password')
    ? { access_token: 'test-access', refresh_token: 'test-refresh', expires_in: 3600, user: { id: 'user-one' } }
    : url.includes('/products') ? [{ id: 'product-one' }] : {};
  return { ok: true, status: 200, text: async () => JSON.stringify(result) };
};
const cloud = new UniLoopCloud({ fetcher, storage });
await assert.rejects(() => cloud.createProduct({ name: 'test' }), error => error instanceof CloudError && error.status === 401);
await cloud.signIn('test@example.invalid', 'test-password');
await cloud.createProduct({ name: 'book', category: 'books', price: 10, city: 'city', school: 'school', owner_id: 'other-user' });
const insert = calls.at(-1);
assert.equal(JSON.parse(insert.body).owner_id, 'user-one');
assert.equal(insert.headers.Authorization, 'Bearer test-access');
await cloud.signOut();
assert.equal(cloud.session, null);
let refreshCalls = 0;
const refreshed = new UniLoopCloud({ storage, fetcher: async (url) => {
  assert.match(url, /grant_type=refresh_token/);
  refreshCalls++;
  return { ok: true, status: 200, text: async () => JSON.stringify({ access_token: 'new-access', refresh_token: 'new-refresh', expires_in: 3600, user: { id: 'user-one' } }) };
} });
storage.setItem('uniloop-cloud-session-v1', JSON.stringify({ access_token: 'old-access', refresh_token: 'old-refresh', expires_at: 1, user: { id: 'user-one' } }));
const sessions = await Promise.all([refreshed.getSession(), refreshed.getSession()]);
assert.equal(refreshCalls, 1);
assert.equal(sessions[0].access_token, 'new-access');
assert.equal(sessions[1].access_token, 'new-access');
let uploadRequest;
const uploadCloud = new UniLoopCloud({ storage, fetcher: async (url, opts) => {
  uploadRequest = { url, ...opts };
  return { ok: true, status: 200, text: async () => '{}' };
} });
const image = new File(['abc'], 'demo.png', { type: 'image/png' });
const uploaded = await uploadCloud.uploadProductImage(image);
assert.match(uploaded.path, /^user-one\/[a-f0-9-]+\.png$/);
assert.match(uploadRequest.url, /\/storage\/v1\/object\/Uniloop-product-images\/user-one\//);
assert.equal(uploadRequest.headers.Authorization, 'Bearer new-access');
await assert.rejects(() => uploadCloud.uploadProductImage(new File(['x'], 'bad.txt', { type: 'text/plain' })), /JPG/);
await cloud.signIn('test@example.invalid', 'test-password');
await cloud.listMyProducts();
assert.match(calls.at(-1).url, /owner_id=eq.user-one/);
await cloud.updateProduct('product-one', { name: 'updated', price: 20, owner_id: 'other-user', status: '交易完成' });
assert.match(calls.at(-1).url, /owner_id=eq.user-one/);
assert.deepEqual(JSON.parse(calls.at(-1).body), { name: 'updated', price: 20 });
await cloud.listMessages('chat-one');
assert.match(calls.at(-1).url, /messages\?conversation_id=eq.chat-one/);
await cloud.sendMessage('chat-one', 'hello');
assert.deepEqual(JSON.parse(calls.at(-1).body), { conversation_id:'chat-one', sender_id:'user-one', body:'hello' });
await cloud.markConversationRead('chat-one', '2026-11-06T10:00:00Z');
assert.match(calls.at(-1).url, /conversation_reads\?on_conflict=conversation_id,user_id/);
assert.deepEqual(JSON.parse(calls.at(-1).body), { conversation_id:'chat-one', user_id:'user-one', last_read_at:'2026-11-06T10:00:00Z' });
await cloud.createTrade('product-one', '買賣');
assert.match(calls.at(-1).url, /rpc\/create_trade_request/);
assert.deepEqual(JSON.parse(calls.at(-1).body), { p_product_id:'product-one', p_method:'買賣' });
await cloud.transitionTrade('trade-one', '已取消', '測試原因');
assert.deepEqual(JSON.parse(calls.at(-1).body), { p_id:'trade-one', p_status:'已取消', p_reason:'測試原因' });
await cloud.importLegacyProduct({ name: 'book', category: 'books', price: 10, city: 'city', school: 'school', owner_id: 'other-user' }, 'legacy-v1-test');
const imported = calls.at(-1);
assert.match(imported.url, /on_conflict=owner_id,legacy_source_key/);
assert.equal(imported.headers.Prefer, 'resolution=ignore-duplicates,return=representation');
assert.equal(JSON.parse(imported.body).owner_id, 'user-one');
assert.equal(JSON.parse(imported.body).legacy_source_key, 'legacy-v1-test');
await cloud.addFavorite('product-one');
const favoriteInsert = calls.at(-1);
assert.match(favoriteInsert.url, /favorites\?on_conflict=user_id,product_id/);
assert.deepEqual(JSON.parse(favoriteInsert.body), { user_id: 'user-one', product_id: 'product-one' });
assert.equal(favoriteInsert.headers.Authorization, 'Bearer test-access');
await cloud.listFavorites();
assert.match(calls.at(-1).url, /user_id=eq.user-one/);
await cloud.removeFavorite('product-one');
assert.match(calls.at(-1).url, /user_id=eq.user-one&product_id=eq.product-one/);
assert.equal(calls.at(-1).method, 'DELETE');
await cloud.signOut();
await assert.rejects(() => cloud.addFavorite('product-one'), error => error.status === 401);
console.log('雲端連線層的登入、商品建立與登出檢查通過（模擬服務）。');
